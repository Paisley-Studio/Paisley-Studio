"""Lay the narration out on the timeline and write src/timeline.json.

Each line is placed so that its *speech* (not the TTS file's padding) starts exactly the
script's pause after the previous line's speech ends. Word timings come along so the picture
and the sound effects can land on spoken words.

Usage: python production/layout.py
"""
import json
import os
import sys
import wave

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from script import LINES, SCENES, SCENE_LEAD, DEFAULT_LEAD, BPM, events  # noqa: E402
from gen_vo import VOICE  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FPS = 30


def speech_bounds(path):
    with wave.open(path) as w:
        sr = w.getframerate()
        x = np.frombuffer(w.readframes(w.getnframes()), np.int16).astype(np.float64) / 32768
    hop = int(0.01 * sr)
    rms = np.sqrt(np.convolve(x ** 2, np.ones(hop) / hop, "same"))[::hop]
    on = np.where(rms > 10 ** (-42 / 20))[0]
    return on[0] * 0.01, (on[-1] + 1) * 0.01, len(x) / sr


words = json.load(open(os.path.join(ROOT, "production", "audio", "takes", VOICE, "words.json"), encoding="utf-8"))
vo, scenes = [], {}
cursor = 0.0  # where the previous line's speech ended, plus its pause
prev_scene = None
for lid, text, pause in LINES:
    scene = lid[:3]
    s0, s1, dur = speech_bounds(os.path.join(ROOT, "production", "audio", "vo", f"{lid}.wav"))
    if scene != prev_scene:
        cursor += SCENE_LEAD.get(scene, DEFAULT_LEAD)
        scenes[scene] = round(cursor - min(0.12, SCENE_LEAD.get(scene, DEFAULT_LEAD)) if prev_scene else 0.0, 3)  # the cut lands just before the voice
        prev_scene = scene
    at = cursor - s0
    vo.append({
        "id": lid, "text": text, "file": f"{lid}.wav", "at": round(at, 3), "speech": [round(cursor, 3), round(at + s1, 3)],
        "words": [[round(at + a, 3), round(at + b, 3), w] for a, b, w in words[lid]],
    })
    cursor = at + s1 + pause

duration = round(cursor + 0.2, 2)
ids = list(scenes)
bounds = {k: [scenes[k], scenes[ids[i + 1]] if i + 1 < len(ids) else duration] for i, k in enumerate(ids)}
by_id = {l["id"]: l for l in vo}


def _clean(w):
    return "".join(c for c in w.lower() if c.isalnum() or c == "'")


def _w(lid, word):
    return next(a for a, _, w in by_id[lid]["words"] if _clean(w) == word)


EV = {k: (round(v, 3) if isinstance(v, float) else v) for k, v in
      events(lambda i: by_id[i]["speech"][0], lambda i: by_id[i]["speech"][1], _w).items()}
out = {
    "_comment": "Generated by production/layout.py from production/script.py. All times in seconds. Do not edit by hand.",
    "fps": FPS, "duration": duration, "bpm": BPM, "events": EV,
    "sceneTitles": dict(SCENES), "scenes": bounds, "vo": vo,
}
with open(os.path.join(ROOT, "src", "timeline.json"), "w", encoding="utf-8") as f:
    json.dump(out, f, indent=1)
print(f"duration {duration:.1f}s ({int(duration // 60)}:{duration % 60:04.1f})")
for k, (a, b) in bounds.items():
    print(f"  {k} {a:7.2f} - {b:7.2f}  ({b - a:5.1f}s)  {dict(SCENES)[k]}")
