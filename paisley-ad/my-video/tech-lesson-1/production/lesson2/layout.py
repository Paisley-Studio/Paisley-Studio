"""Lay Lesson 2's narration out on the timeline and write src/lesson2/timeline.json.

Works like production/layout.py (speech starts exactly the script's pause after the previous line's
speech ends), with one addition: the lesson must last exactly script.TARGET seconds, so the time left
over is shared between the FLEX pauses by weight.

Usage: python production/lesson2/layout.py
"""
import json
import os
import sys
import wave

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from script import LINES, SCENES, SCENE_LEAD, DEFAULT_LEAD, FLEX, TARGET  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(HERE))
FPS = 30
TAIL = 0.2  # after the last line's pause


def speech_bounds(path):
    with wave.open(path) as w:
        sr = w.getframerate()
        x = np.frombuffer(w.readframes(w.getnframes()), np.int16).astype(np.float64) / 32768
    hop = int(0.01 * sr)
    rms = np.sqrt(np.convolve(x ** 2, np.ones(hop) / hop, "same"))[::hop]
    on = np.where(rms > 10 ** (-42 / 20))[0]
    return on[0] * 0.01, (on[-1] + 1) * 0.01, len(x) / sr


words = json.load(open(os.path.join(HERE, "audio", "takes", "words.json"), encoding="utf-8"))
bounds_of = {lid: speech_bounds(os.path.join(HERE, "audio", "vo", f"{lid}.wav")) for lid, _, _ in LINES}


def lay(extra):
    vo, scenes = [], {}
    cursor, prev_scene = 0.0, None
    for lid, text, pause in LINES:
        scene = lid[:3]
        s0, s1, _ = bounds_of[lid]
        if scene != prev_scene:
            cursor += SCENE_LEAD.get(scene, DEFAULT_LEAD)
            scenes[scene] = round(cursor - 0.45 if prev_scene else 0.0, 3)
            prev_scene = scene
        at = cursor - s0
        vo.append({
            "id": lid, "text": text, "file": f"{lid}.wav", "at": round(at, 3), "speech": [round(cursor, 3), round(at + s1, 3)],
            "words": [[round(at + a, 3), round(at + b, 3), w] for a, b, w in words[lid]],
        })
        cursor = at + s1 + pause + extra.get(lid, 0.0)
    return vo, scenes, cursor + TAIL


_, _, natural = lay({})
spare = TARGET - natural
if spare < 0:
    sys.exit(f"The script runs {natural:.1f}s, {-spare:.1f}s over the {TARGET:.0f}s target: trim lines or pauses.")
total_w = sum(FLEX.values())
extra = {k: spare * w / total_w for k, w in FLEX.items()}
vo, scenes, end = lay(extra)
duration = TARGET
ids = list(scenes)
bounds = {k: [scenes[k], scenes[ids[i + 1]] if i + 1 < len(ids) else duration] for i, k in enumerate(ids)}
out = {
    "_comment": "Generated by production/lesson2/layout.py from production/lesson2/script.py. All times in seconds. Do not edit by hand.",
    "fps": FPS, "duration": duration,
    "sceneTitles": dict(SCENES), "scenes": bounds, "flex": {k: round(v, 3) for k, v in extra.items()}, "vo": vo,
}
os.makedirs(os.path.join(ROOT, "src", "lesson2"), exist_ok=True)
with open(os.path.join(ROOT, "src", "lesson2", "timeline.json"), "w", encoding="utf-8") as f:
    json.dump(out, f, indent=1)
print(f"natural {natural:.1f}s, spare {spare:.1f}s shared over {len(FLEX)} pauses -> {duration:.1f}s")
for k, v in extra.items():
    print(f"  +{v:5.1f}s after {k}")
for k, (a, b) in bounds.items():
    print(f"  {k} {a:7.2f} - {b:7.2f}  ({b - a:5.1f}s)  {dict(SCENES)[k]}")
